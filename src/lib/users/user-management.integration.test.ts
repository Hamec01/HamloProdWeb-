import { PrismaClient } from "@prisma/client";
import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { prisma } from "@/lib/db/client";
import { addPrivateNote, getUserConversation, sendUserMessage, listPrivateNotes, grantUserPoints, listPointGrants, unreadCustomerMessage, unreadProducerMessage, userSearchWhere } from "./service";
import { grantInput, noteInput, messageInput } from "./validation";
const enabled = process.env.LICENSE_INTEGRATION_TEST === "1";

test("user management: private general chat, notes, paged history and atomic audited grants", { skip: !enabled, timeout: 45000 }, async (t) => {
  assert.ok(new URL(process.env.DATABASE_URL!).pathname.endsWith("/hamloprod_license_test"));
  const concurrent = new PrismaClient({ datasourceUrl: process.env.DATABASE_URL });
  const ids: string[] = [];
  const makeUser = async (role: "USER" | "ADMIN" | "EDITOR" = "USER") => { const user = await prisma.user.create({ data: { email: `users-${randomUUID()}@example.invalid`, displayName: `Artist ${randomUUID()}`, role } }); ids.push(user.id); return user; };
  t.after(async () => {
    await concurrent.$disconnect();
    // Restricted author FKs preserve audit records; remove owned fixtures first.
    await prisma.adminUserNote.deleteMany({ where: { userId: { in: ids } } });
    await prisma.loyaltyGrant.deleteMany({ where: { userId: { in: ids } } });
    await prisma.user.deleteMany({ where: { id: { in: ids } } });
    await prisma.$disconnect();
  });
  const admin = await makeUser("ADMIN"), buyer = await makeUser(), other = await makeUser(), editor = await makeUser("EDITOR");
  const producer = { userId: admin.id, role: "admin" as const }, owner = { userId: buyer.id, role: "buyer" as const }, outsider = { userId: other.id, role: "buyer" as const };
  assert.equal((await getUserConversation(buyer.id, owner)).messages.length, 0);
  assert.equal(await prisma.userConversation.count({ where: { userId: buyer.id } }), 0, "read does not create an empty thread");
  await assert.rejects(getUserConversation(buyer.id, outsider), /USER_NOT_FOUND/);
  await assert.rejects(getUserConversation(buyer.id, { userId: other.id, role: "admin" }), /FORBIDDEN/);
  await assert.rejects(sendUserMessage(buyer.id, outsider, "foreign", randomUUID()), /USER_NOT_FOUND/);
  const nonce = randomUUID();
  const sent = await sendUserMessage(buyer.id, producer, "Привет! <script>alert(1)</script>", nonce);
  assert.equal((await sendUserMessage(buyer.id, producer, "Привет! <script>alert(1)</script>", nonce)).id, sent.id);
  await assert.rejects(sendUserMessage(buyer.id, producer, "changed", nonce), /REQUEST_CONFLICT/);
  assert.ok(unreadProducerMessage(await prisma.userConversation.findUniqueOrThrow({ where: { userId: buyer.id } })));
  const received = await getUserConversation(buyer.id, owner);
  assert.equal(received.messages[0].text, "Привет! <script>alert(1)</script>");
  assert.ok(!unreadProducerMessage(await prisma.userConversation.findUniqueOrThrow({ where: { userId: buyer.id } })));
  await sendUserMessage(buyer.id, owner, "Спасибо, какой бит выбрать?", randomUUID());
  assert.ok(unreadCustomerMessage(await prisma.userConversation.findUniqueOrThrow({ where: { userId: buyer.id } })));
  await getUserConversation(buyer.id, producer);
  assert.ok(!unreadCustomerMessage(await prisma.userConversation.findUniqueOrThrow({ where: { userId: buyer.id } })));
  const baseline = Date.now() - 100000;
  await prisma.userMessage.createMany({ data: Array.from({ length: 53 }, (_, index) => ({ userId: buyer.id, authorId: buyer.id, authorRole: "buyer", text: `history ${index}`, clientMessageId: randomUUID(), createdAt: new Date(baseline + index) })) });
  const latest = await getUserConversation(buyer.id, owner);
  const older = await getUserConversation(buyer.id, owner, latest.messages[0].id);
  assert.equal(latest.messages.length, 50); assert.ok(latest.hasMore);
  assert.equal(older.messages.length, 5); assert.equal(older.hasMore, false);
  assert.equal(new Set([...latest.messages, ...older.messages].map((m) => m.id)).size, 55);
  const foreign = await sendUserMessage(other.id, producer, "other thread", randomUUID());
  await assert.rejects(getUserConversation(buyer.id, owner, foreign.id), /BAD_CURSOR/);
  const noteId = randomUUID();
  await addPrivateNote(buyer.id, admin.id, "PRIVATE: согласован особый прайс", noteId);
  await addPrivateNote(buyer.id, admin.id, "PRIVATE: согласован особый прайс", noteId);
  assert.equal((await listPrivateNotes(buyer.id, admin.id)).items.length, 1);
  await assert.rejects(listPrivateNotes(buyer.id, buyer.id), /FORBIDDEN/);
  await assert.rejects(addPrivateNote(buyer.id, editor.id, "wrong", randomUUID()), /FORBIDDEN/);
  await assert.rejects(addPrivateNote(other.id, admin.id, "PRIVATE: согласован особый прайс", noteId), /REQUEST_CONFLICT/);
  assert.ok(!JSON.stringify(await getUserConversation(buyer.id, owner)).includes("PRIVATE"));
  await prisma.adminUserNote.createMany({ data: Array.from({ length: 21 }, (_, i) => ({ id: randomUUID(), userId: buyer.id, authorId: admin.id, text: `private ${i}` })) });
  const notePage = await listPrivateNotes(buyer.id, admin.id);
  assert.equal(notePage.items.length, 20); assert.ok(notePage.hasMore);
  assert.equal((await listPrivateNotes(buyer.id, admin.id, notePage.items.at(-1)!.id)).items.length, 2);
  await assert.rejects(grantUserPoints(buyer.id, editor.id, 25, "wrong", randomUUID()), /FORBIDDEN/);
  const grantId = randomUUID();
  const duplicate = await Promise.all([grantUserPoints(buyer.id, admin.id, 25, "Подарок артисту", grantId), grantUserPoints(buyer.id, admin.id, 25, "Подарок артисту", grantId, concurrent)]);
  assert.equal(duplicate[0].id, duplicate[1].id);
  assert.equal((await prisma.loyaltyPoint.findUniqueOrThrow({ where: { userId: buyer.id } })).points, 25);
  assert.equal(await prisma.loyaltyGrant.count({ where: { userId: buyer.id } }), 1);
  await assert.rejects(grantUserPoints(buyer.id, admin.id, 100, "changed", grantId), /REQUEST_CONFLICT/);
  await Promise.all([grantUserPoints(buyer.id, admin.id, 25, "Ещё бонус", randomUUID()), grantUserPoints(buyer.id, admin.id, 50, "Приз", randomUUID(), concurrent)]);
  assert.equal((await prisma.loyaltyPoint.findUniqueOrThrow({ where: { userId: buyer.id } })).points, 100);
  assert.equal((await listPointGrants(buyer.id)).items.reduce((sum, grant) => sum + grant.amount, 0), 100);
  // A concurrent spend and a credit must both survive the atomic balance writes.
  await Promise.all([grantUserPoints(buyer.id, admin.id, 25, "После обмена", randomUUID()), concurrent.loyaltyPoint.updateMany({ where: { userId: buyer.id, points: { gte: 100 } }, data: { points: { decrement: 100 } } })]);
  assert.equal((await prisma.loyaltyPoint.findUniqueOrThrow({ where: { userId: buyer.id } })).points, 25);
  await prisma.loyaltyPoint.update({ where: { userId: buyer.id }, data: { points: 2147483647 } });
  await assert.rejects(grantUserPoints(buyer.id, admin.id, 1, "Overflow", randomUUID()), /BALANCE_LIMIT/);
  assert.equal(await prisma.loyaltyGrant.count({ where: { userId: buyer.id } }), 4);
  const found = await prisma.user.findMany({ where: userSearchWhere(buyer.email.toUpperCase()), select: { id: true } });
  assert.deepEqual(found.map((u) => u.id), [buyer.id]);
});

test("manual point credits and message/note inputs reject invalid or forged payloads", () => {
  const valid = { amount: 25, reason: "Bonus", requestId: randomUUID() };
  assert.ok(grantInput.safeParse(valid).success);
  for (const amount of [0, -25, 0.5, 10001, "25"]) assert.ok(!grantInput.safeParse({ ...valid, amount }).success);
  assert.ok(!grantInput.safeParse({ ...valid, reason: " " }).success);
  assert.ok(!grantInput.safeParse({ ...valid, role: "ADMIN" }).success);
  assert.ok(!noteInput.safeParse({ text: " ", requestId: randomUUID() }).success);
  assert.ok(!messageInput.safeParse({ text: "hello", clientMessageId: randomUUID(), authorRole: "admin" }).success);
});
