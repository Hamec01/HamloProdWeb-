import { PrismaClient } from "@prisma/client";
import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { prisma } from "@/lib/db/client";
import { createBeatInquiry } from "./inquiries";
import { getConversation, sendOrderMessage } from "./conversation";
import { reserveOrderBeat, cancelOrderReservation, releaseExpiredReservations, RESERVATION_MS, checkBeatForBuyer } from "./reservations";
import { lockBeatForExclusiveSale } from "./exclusive-sale";
import { redeemBeatOrder } from "@/lib/loyalty/redeem-order";
import { awardSalePoints } from "@/lib/loyalty/award-sale";
import { renderContractHtml } from "@/lib/contracts/preview";
import { toOrderRow } from "@/lib/orders/order-row";
import { ContaboS3Storage } from "@/lib/storage/contabo-s3-storage";
import { getS3Config } from "@/lib/storage/config";

const enabled = process.env.LICENSE_INTEGRATION_TEST === "1";

test("RF requests: private messages, weekly reservations, expiry and atomic 100-point redemption", { skip: !enabled, timeout: 120_000 }, async (t) => {
  assert.ok(new URL(process.env.DATABASE_URL!).pathname.endsWith("/hamloprod_license_test"));
  const concurrentClient = new PrismaClient({ datasourceUrl: process.env.DATABASE_URL });
  const beatIds: string[] = [];
  const userIds: string[] = [];
  const user = async (role: "USER" | "ADMIN" = "USER") => { const record = await prisma.user.create({ data: { email: `chat-${randomUUID()}@example.invalid`, role } }); userIds.push(record.id); return record; };
  const makeBeat = async () => { const suffix = randomUUID(); const record = await prisma.beat.create({ data: { title: "Reservation test", caseNumber: `CHAT-${suffix}`, slug: `chat-${suffix}`, genre: "trap", priceUsd: 100, priceRub: 2500, status: "available", publishedAt: new Date() } }); beatIds.push(record.id); return record; };
  t.after(async () => {
    await concurrentClient.$disconnect();
    const orders = await prisma.order.findMany({ where: { beatId: { in: beatIds } }, select: { contractPdfKey: true } });
    const storage = new ContaboS3Storage(getS3Config());
    for (const order of orders) if (order.contractPdfKey) await storage.deleteObject({ visibility: "private", key: order.contractPdfKey });
    await prisma.order.deleteMany({ where: { beatId: { in: beatIds } } });
    await prisma.beat.deleteMany({ where: { id: { in: beatIds } } });
    await prisma.user.deleteMany({ where: { id: { in: userIds } } });
    await prisma.$disconnect();
  });
  const first = await user(), second = await user(), admin = await user("ADMIN");
  const actor = { userId: first.id, role: "buyer" as const }, stranger = { userId: second.id, role: "buyer" as const }, producer = { userId: admin.id, role: "admin" as const };
  const beat = await makeBeat();
  const [request, repeated] = await Promise.all([createBeatInquiry(beat.id, { userId: first.id, email: first.email }, "ru", false), createBeatInquiry(beat.id, { userId: first.id, email: first.email }, "ru", false)]);
  assert.equal(request.orderId, repeated.orderId);
  assert.equal((await prisma.order.findUniqueOrThrow({ where: { id: request.orderId } })).currency, "RUB");
  const other = await createBeatInquiry(beat.id, { userId: second.id, email: second.email }, "ru", false);
  const nonce = randomUUID();
  const message = await sendOrderMessage(request.orderId, actor, "Как оплатить? <script>alert(1)</script>", nonce);
  assert.equal((await sendOrderMessage(request.orderId, actor, "Как оплатить? <script>alert(1)</script>", nonce)).id, message.id);
  await assert.rejects(getConversation(request.orderId, stranger), /ORDER_NOT_FOUND/);
  await assert.rejects(sendOrderMessage(request.orderId, stranger, "wrong", randomUUID()), /ORDER_NOT_FOUND/);
  const incoming = await getConversation(request.orderId, producer);
  assert.ok(incoming.messages.some((entry) => entry.id === message.id));
  assert.ok((await prisma.order.findUniqueOrThrow({ where: { id: request.orderId } })).adminLastReadAt);
  await sendOrderMessage(request.orderId, producer, "Можно оплатить переводом. После подтверждения выдам PDF.", randomUUID());
  assert.ok((await getConversation(request.orderId, actor)).messages.some((entry) => entry.role === "admin"));
  await prisma.orderMessage.createMany({ data: Array.from({ length: 51 }, (_, index) => ({ orderId: request.orderId, authorRole: "buyer", authorUserId: first.id, text: `history ${index}` })) });
  const newestPage = await getConversation(request.orderId, actor);
  assert.equal(newestPage.messages.length, 50); assert.equal(newestPage.hasMore, true);
  const olderPage = await getConversation(request.orderId, actor, newestPage.messages[0].id);
  assert.equal(olderPage.messages.length, 4); assert.equal(olderPage.hasMore, false);
  assert.equal(new Set([...olderPage.messages, ...newestPage.messages].map((message) => message.id)).size, 54);
  const before = Date.now();
  const until = await prisma.$transaction((tx) => reserveOrderBeat(tx, request.orderId, actor));
  assert.ok(until.getTime() >= before + RESERVATION_MS && until.getTime() <= Date.now() + RESERVATION_MS);
  assert.equal((await prisma.$transaction((tx) => reserveOrderBeat(tx, request.orderId, actor))).toISOString(), until.toISOString());
  await assert.rejects(prisma.$transaction((tx) => reserveOrderBeat(tx, other.orderId, stranger)), /BEAT_RESERVED/);
  await assert.rejects(prisma.$transaction((tx) => checkBeatForBuyer(tx, beat.id, second.id)), /BEAT_RESERVED/);
  assert.equal(await prisma.$transaction((tx) => lockBeatForExclusiveSale(tx, beat.id, second.id)), false);
  await assert.rejects(prisma.$transaction((tx) => cancelOrderReservation(tx, request.orderId, stranger)), /ORDER_NOT_FOUND/);
  await prisma.$transaction((tx) => cancelOrderReservation(tx, request.orderId, actor));
  const simultaneous = await Promise.allSettled([prisma.$transaction((tx) => reserveOrderBeat(tx, request.orderId, actor)), concurrentClient.$transaction((tx) => reserveOrderBeat(tx, other.orderId, stranger))]);
  assert.equal(simultaneous.filter((entry) => entry.status === "fulfilled").length, 1);
  await prisma.beat.update({ where: { id: beat.id }, data: { reservationExpiresAt: new Date(Date.now() - 1000) } });
  await releaseExpiredReservations();
  const released = await prisma.beat.findUniqueOrThrow({ where: { id: beat.id } });
  assert.equal(released.status, "available"); assert.equal(released.reservationOrderId, null);
  const expiryMessages = await prisma.orderMessage.count({ where: { orderId: { in: [request.orderId, other.orderId] }, text: { contains: "Срок брони истёк" } } });
  assert.equal(expiryMessages, 1);
  await releaseExpiredReservations();
  assert.equal(await prisma.orderMessage.count({ where: { orderId: { in: [request.orderId, other.orderId] }, text: { contains: "Срок брони истёк" } } }), 1);
  await prisma.$transaction((tx) => reserveOrderBeat(tx, other.orderId, stranger));
  assert.equal(await prisma.$transaction((tx) => lockBeatForExclusiveSale(tx, beat.id, second.id)), true);
  await releaseExpiredReservations(); assert.equal((await prisma.beat.findUniqueOrThrow({ where: { id: beat.id } })).status, "sold");

  const rewardBuyer = await user();
  await prisma.loyaltyPoint.create({ data: { userId: rewardBuyer.id, userEmail: rewardBuyer.email, points: 75 } });
  const paidBeat = await makeBeat();
  const paid = await prisma.order.create({ data: { beatId: paidBeat.id, buyerUserId: rewardBuyer.id, buyerEmail: rewardBuyer.email, basePriceUsd: 100, finalPriceUsd: 100, basePrice: 100, finalPrice: 100, status: "paid" } });
  assert.equal(await prisma.$transaction((tx) => awardSalePoints(tx, paid.id)), true);
  assert.equal(await prisma.$transaction((tx) => awardSalePoints(tx, paid.id)), false);
  assert.equal((await prisma.loyaltyPoint.findUniqueOrThrow({ where: { userId: rewardBuyer.id } })).points, 100);
  const freeOrders = [];
  for (let index = 0; index < 2; index++) {
    const freeBeat = await makeBeat();
    const order = await prisma.order.create({ data: { beatId: freeBeat.id, buyerUserId: rewardBuyer.id, buyerEmail: rewardBuyer.email, buyerName: "Rewards Buyer", buyerCity: "Turku", buyerCountry: "Finland", basePriceUsd: 100, finalPriceUsd: 0, basePrice: 100, finalPrice: 0, discountPercent: 100, provider: "contact", termsAcceptedAt: new Date(), personalDataConsentAt: new Date() } });
    const html = await renderContractHtml(toOrderRow(order), freeBeat);
    await prisma.contract.create({ data: { orderId: order.id, beatId: freeBeat.id, buyerEmail: order.buyerEmail, htmlSnapshot: html } });
    freeOrders.push(order);
  }
  const redemptions = await Promise.allSettled(freeOrders.map((order, index) => redeemBeatOrder(order.id, rewardBuyer.id, index === 0 ? prisma : concurrentClient)));
  assert.equal(redemptions.filter((entry) => entry.status === "fulfilled").length, 1);
  assert.ok(redemptions.some((entry) => entry.status === "rejected" && /INSUFFICIENT_POINTS/.test(String(entry.reason))));
  const winner = await prisma.order.findFirstOrThrow({ where: { buyerUserId: rewardBuyer.id, loyaltyPointsSpent: 100 } });
  assert.equal((await redeemBeatOrder(winner.id, rewardBuyer.id)).pdfReady, true);
  assert.equal((await prisma.loyaltyPoint.findUniqueOrThrow({ where: { userId: rewardBuyer.id } })).points, 0);
  assert.equal(await prisma.order.count({ where: { id: { in: freeOrders.map((order) => order.id) }, status: "paid" } }), 1);
  assert.equal((await prisma.beatPurchase.findFirstOrThrow({ where: { orderId: winner.id } })).pointsEarned, 0);
  assert.equal(await prisma.$transaction((tx) => awardSalePoints(tx, winner.id)), false);
});
